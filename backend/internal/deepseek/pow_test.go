// TestDeepSeekHashV1Vectors pins the hash to digests produced by
// lib/deepseek-pow.js so the Go solver stays byte-compatible.
func TestDeepSeekHashV1Vectors(t *testing.T) {
	vectors := []struct {
		message string
		digest  string
	}{
		{"", "e594808bc5b7151ac160c6d39a02e0a8e261ed588578403099e3561dc40c26b3"},
		{"abc", "f841106c601ce9be9bc38525e90d4178d47f21dd8eb9f238fc55ffaa4ca94506"},
		{"The quick brown fox jumps over the lazy dog", "9a7f4e87d535e6fff80182224c6c4ddf5ab4042314bd07714b56ff5c55384811"},
		{"salt_123_exp_", "b205604db6db72766c271f966f5d704831f6f59c9bacd5651065fad6ef212b6d"},
		{"salt_123_exp_42", "60ff3d838475d0f7bdeec6c81f12e9fa486f450209253def6242b35db8aad819"},
		{strings.Repeat("a", 135), "1e3eb415bb0b3ecec08a6f71cf7c8d0591b5594752ba52802a2e60357834f998"},
		{strings.Repeat("a", 136), "680364b336f77918ed390287a581f96f1371599825acd1e348fa7649fcecbbab"},
		{strings.Repeat("a", 137), "dfeb7768d4d48053c083d849570e84cc8120520790f2d09cb56e40038081fab4"},
		{strings.Repeat("a", 300), "aebd681138ca094c309f0b1c7018695f76b9b3b64ce2e2195036a4ceedc427fe"},
		// Exactly two rate blocks: exercises the reference solver's lane
		// wrap-around, which drops most of the second block.
		{strings.Repeat("a", 272), "b09e26acb4dd44cb5b18a6de6f0e6e3d594813d8156b1f1030c34c3c831b5a4d"},
		{strings.Repeat("a", 409), "701078b00e0f5b6a086b6d7eeec3a4adb2aad8fa854789512a1a54e9d0e3008a"},
		{"üñïçødé ✓ 漢字", "6a683a7e37a7bf66f3e73e1d8fc77988d0b58de8190dc8186c87f5b8b8c9b696"},
	}
	for _, vector := range vectors {
		digest := deepSeekHashV1([]byte(vector.message))
		if got := hex.EncodeToString(digest[:]); got != vector.digest {
			t.Fatalf("hash(%q) = %s, want %s", vector.message, got, vector.digest)
		}
	}
}

// TestSolvePow checks the solver against a challenge generated by hand: the
// digest of "mySalt_9999999999999_1234" must be answered with nonce 1234.
func TestSolvePow(t *testing.T) {
	challenge := powChallenge{
		Algorithm:  "DeepSeekHashV1",
		Challenge:  "b8f510f48da9815bb9a7ee35a6823ab17fd4d3de82e69d967dcd538a8675b09f",
		Salt:       "mySalt",
		Difficulty: 5000,
		ExpireAt:   9999999999999,
		TargetPath: "/api/v0/chat/completion",
	}
	answer, err := solvePow(context.Background(), challenge)
	if err != nil {
		t.Fatalf("solvePow returned error: %v", err)
	}
	if answer != 1234 {
		t.Fatalf("solvePow = %d, want 1234", answer)
	}
}

// TestSolvePowRejectsUnknownAlgorithm mirrors the JS guard.
func TestSolvePowRejectsUnknownAlgorithm(t *testing.T) {
	_, err := solvePow(context.Background(), powChallenge{Algorithm: "nope"})
	if err == nil || !strings.Contains(err.Error(), "Unsupported algorithm") {
		t.Fatalf("expected unsupported algorithm error, got %v", err)
	}
}
